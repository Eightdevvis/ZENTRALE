    Substitute    = { fg = p.search_fg,    bg = p.search_bg },
    QuickFixLine  = { bg = p.bg_sel },

    -- ── Fenster-Chrom ───────────────────────────────────────────────────
    StatusLine    = { fg = p.status_fg,    bg = p.status_bg, bold = true },
    StatusLineNC  = { fg = p.status_nc_fg, bg = p.status_nc_bg },
