  local g = {
    -- ── Grundflächen ────────────────────────────────────────────────────
    Normal        = { fg = p.fg, bg = p.bg },
    NormalNC      = { fg = p.fg, bg = p.bg },
    NormalFloat   = { fg = p.fg, bg = p.bg_alt },
    FloatBorder   = { fg = p.border, bg = p.bg_alt },
    FloatTitle    = { fg = p.title, bg = p.bg_alt, bold = true },
    Cursor        = { fg = p.bg, bg = p.accent },
    lCursor       = { fg = p.bg, bg = p.accent },
    TermCursor    = { fg = p.bg, bg = p.accent },
    CursorLine    = { bg = p.bg_dim },
    CursorColumn  = { bg = p.bg_dim },
    ColorColumn   = { bg = p.bg_dim },
    LineNr        = { fg = p.line_nr, bg = p.bg },
    LineNrAbove   = { fg = p.line_nr, bg = p.bg },
    LineNrBelow   = { fg = p.line_nr, bg = p.bg },
    CursorLineNr  = { fg = p.line_nr_cur, bg = p.bg_dim, bold = true },
    SignColumn    = { fg = p.line_nr, bg = p.bg },
    FoldColumn    = { fg = p.line_nr, bg = p.bg },
    Folded        = { fg = p.fg_faint, bg = p.bg_alt },
    Visual        = { bg = p.bg_sel },
    VisualNOS     = { bg = p.bg_sel },
    MatchParen    = { fg = p.accent, bg = p.bg_match, bold = true },
    Whitespace    = { fg = p.line_nr },
    NonText       = { fg = p.line_nr },
    EndOfBuffer   = { fg = p.line_nr },
    SpecialKey    = { fg = p.special },
    Conceal       = { fg = p.fg_dim },
    Directory     = { fg = p.accent },
    Title         = { fg = p.title, bold = true },
    Question      = { fg = p.ok },
    MoreMsg       = { fg = p.ok },
    ModeMsg       = { fg = p.fg_dim, bold = true },
    MsgArea       = { fg = p.fg, bg = p.bg },
    MsgSeparator  = { fg = p.border, bg = p.bg },
    ErrorMsg      = { fg = p.error, bold = true },
    WarningMsg    = { fg = p.warn },

    -- ── Suche ───────────────────────────────────────────────────────────
