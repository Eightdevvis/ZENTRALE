    ["@property"]           = { fg = p.property },
    ["@field"]              = { fg = p.property },
    ["@module"]             = { fg = p.type },
    ["@constant"]           = { fg = p.constant },
    ["@constant.builtin"]   = { fg = p.constant, italic = true },
    ["@function"]           = { fg = p.accent },
    ["@function.builtin"]   = { fg = p.accent, italic = true },
    ["@function.call"]      = { fg = p.accent },
    ["@function.method"]    = { fg = p.accent },
    ["@constructor"]        = { fg = p.type },
    ["@keyword"]            = { fg = p.keyword },
    ["@keyword.return"]     = { fg = p.keyword, bold = true },
    ["@type"]               = { fg = p.type },
    ["@type.builtin"]       = { fg = p.type, italic = true },
    ["@attribute"]          = { fg = p.special },
    ["@string"]             = { fg = p.string },
    ["@string.escape"]      = { fg = p.special },
    ["@string.special"]     = { fg = p.special },
    ["@operator"]           = { fg = p.fg_dim },
    ["@punctuation.delimiter"] = { fg = p.fg_dim },
    ["@punctuation.bracket"]   = { fg = p.fg_dim },
    ["@punctuation.special"]   = { fg = p.special },
    ["@comment"]            = { fg = p.fg_faint, italic = it },
    ["@comment.error"]      = { fg = p.todo_fg, bg = p.error, bold = true },
