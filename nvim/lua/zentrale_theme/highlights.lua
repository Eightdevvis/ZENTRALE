    Type          = { fg = p.type },
    StorageClass  = { fg = p.type },
    Structure     = { fg = p.type },
    Typedef       = { fg = p.type },
    Special       = { fg = p.special },
    SpecialChar   = { fg = p.special },
    Tag           = { fg = p.property },
    Delimiter     = { fg = p.fg_dim },
    SpecialComment= { fg = p.fg_dim, italic = it },
    Debug         = { fg = p.warn },
    Underlined    = { fg = p.accent, underline = true },
    Ignore        = { fg = p.fg_faint },
    Error         = { fg = p.error, bold = true },
