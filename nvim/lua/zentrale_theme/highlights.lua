-- zentrale_theme.highlights — Rollen einer Palette → nvim-Highlight-Gruppen.
--
-- EINE Zuordnung für BEIDE Paletten (cyber/paper): die Paletten liefern nur
-- Farben unter gleichnamigen Rollen (siehe palettes.lua), die Struktur steht
-- hier. So kann eine Palette nicht Gruppen vergessen, die die andere hat.

local M = {}

--- Baut die komplette Gruppen-Tabelle für eine Palette.
--- @param p table Palette aus palettes.lua
--- @return table<string, table> group → nvim_set_hl-Attribute
