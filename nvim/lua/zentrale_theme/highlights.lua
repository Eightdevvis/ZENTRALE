    ["@markup.list"]        = { fg = p.special },
    ["@markup.quote"]       = { fg = p.fg_dim, italic = true },
    ["@diff.plus"]          = { fg = p.ok },
    ["@diff.minus"]         = { fg = p.error },
    ["@diff.delta"]         = { fg = p.info },
  }
  return g
end

return M
